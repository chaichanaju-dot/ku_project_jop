# เปลี่ยนเป็น Path ของคุณใน Google Drive
PROJECT_PATH = "/content/drive/MyDrive/phase4/3"

DATASET_ROOT = f"{PROJECT_PATH}/train"
OUTPUT_ROOT = f"{PROJECT_PATH}/train_aug_obb"

IMAGE_DIR = Path(DATASET_ROOT) / "images"
LABEL_DIR = Path(DATASET_ROOT) / "labels"

OUT_IMAGE_DIR = Path(OUTPUT_ROOT) / "images"
OUT_LABEL_DIR = Path(OUTPUT_ROOT) / "labels"
PREVIEW_DIR = Path(OUTPUT_ROOT) / "preview"

# ตั้งค่าการขยายข้อมูล
OUTPUT_SIZE = (640, 640)      # ปรับขนาดภาพปลายทาง
BASE_AUG_PER_IMAGE = 2        # เพิ่มขั้นต่ำกี่เท่าสำหรับภาพปกติ
MAX_EXTRA_AUG_FOR_RARE = 4    # เพิ่มพิเศษให้คลาสที่หาดูยาก
RARE_CLASS_THRESHOLD_RATIO = 0.50
COPY_ORIGINALS = True         # คัดลอกรูปต้นฉบับไปด้วยหรือไม่
SAVE_PREVIEW = True           # สร้างภาพตัวอย่างที่วาดกล่อง OBB หรือไม่

CLASS_NAMES = {
  0: "Crack",
  1: "Efflorescence",
  2: "Porous_Defect",
  3: "Rust_Stained_Exposure",
  4: "Spalling",
  5: "Steel_Exposure",
  6: "strain"
}

