def ensure_dir(path: Path):
    path.mkdir(parents=True, exist_ok=True)

def load_yolo_obb_labels(label_path: Path):
    """ อ่านไฟล์ Label แบบ OBB (มี 9 ค่า: class_id, x1, y1, x2, y2, x3, y3, x4, y4) """
    polygons_norm, class_labels = [], []
    if not label_path.exists(): return polygons_norm, class_labels
    with open(label_path, "r", encoding="utf-8") as f:
        for line in f:
            parts = line.strip().split()
            if len(parts) == 9:
                cls_id = int(float(parts[0]))
                pts = [float(x) for x in parts[1:]]
                # เก็บเป็นคู่พิกัด Normalized (0-1)
                poly = [(pts[0], pts[1]), (pts[2], pts[3]), (pts[4], pts[5]), (pts[6], pts[7])]
                polygons_norm.append(poly)
                class_labels.append(cls_id)
    return polygons_norm, class_labels

def save_yolo_obb_labels(label_path: Path, polygons_abs, class_labels, img_w, img_h):
    """ แปลงพิกัด Pixel จริง กลับเป็น Normalized (0-1) แล้วเซฟไฟล์ """
    with open(label_path, "w", encoding="utf-8") as f:
        for cls_id, poly in zip(class_labels, polygons_abs):
            norm_pts = []
            for x, y in poly:
                # แปลงและป้องกันค่าล้นขอบ (Clipping)
                nx = min(max(x / img_w, 0.0), 1.0)
                ny = min(max(y / img_h, 0.0), 1.0)
                norm_pts.extend([nx, ny])

            line = f"{cls_id} " + " ".join([f"{v:.6f}" for v in norm_pts]) + "\n"
            f.write(line)

def draw_bboxes_obb(image_bgr, polygons_abs, class_labels):
    """ วาดกล่องเอียงลงบนภาพ Preview """
    out = image_bgr.copy()
    for poly, cls_id in zip(polygons_abs, class_labels):
        # แปลงเป็น array สำหรับวาดรูป polygon
        pts = np.array(poly, np.int32).reshape((-1, 1, 2))
        color = (int((37*cls_id)%255), int((17*cls_id+80)%255), int((29*cls_id+160)%255))
        cv2.polylines(out, [pts], isClosed=True, color=color, thickness=2)
        cv2.putText(out, f"{CLASS_NAMES.get(cls_id, cls_id)}", (pts[0][0][0], max(15, pts[0][0][1]-5)), cv2.FONT_HERSHEY_SIMPLEX, 0.5, color, 2)
    return out

# ท่าทางการแปลงภาพ
# **สำคัญ:** เปลี่ยนมาใช้ keypoint_params เพื่อดึงจุด 4 มุมของ OBB ไปหมุนแทน
TRANSFORM = A.Compose([
    A.OneOf([
        A.RandomBrightnessContrast(p=1),
        A.CLAHE(p=1),
        A.HueSaturationValue(p=1),
    ], p=0.7),
    A.HorizontalFlip(p=0.5),
    A.OneOf([
        A.Affine(rotate=(-15, 15), translate_percent=(-0.1, 0.1), p=1),
        A.Perspective(scale=(0.05, 0.1), p=1),
    ], p=0.6),
    A.GaussianBlur(blur_limit=(3, 5), p=0.3),
    A.Resize(height=OUTPUT_SIZE[0], width=OUTPUT_SIZE[1], p=1.0)
], keypoint_params=A.KeypointParams(format="xy", remove_invisible=False))
# remove_invisible=False สำคัญมาก! เพื่อกันไม่ให้จุดมุมหายไประหว่างหมุนภาพ

