# =========================================================
def run_augmentation():
    if not IMAGE_DIR.exists() or not LABEL_DIR.exists():
        print(f"❌ ไม่พบโฟลเดอร์ภาพหรือ Label ใน: {DATASET_ROOT}")
        return

    ensure_dir(OUT_IMAGE_DIR)
    ensure_dir(OUT_LABEL_DIR)
    if SAVE_PREVIEW: ensure_dir(PREVIEW_DIR)

    img_files = sorted([p for p in IMAGE_DIR.iterdir() if p.is_file() and p.suffix.lower() in {".jpg", ".jpeg", ".png"}])
    if not img_files:
        print("❌ ไม่พบไฟล์รูปภาพในโฟลเดอร์ที่ระบุเลยครับ")
        return

    # 1. วิเคราะห์คลาส
    all_classes = []
    img_to_data = {}
    for p in img_files:
        polygons_norm, labels = load_yolo_obb_labels(LABEL_DIR / f"{p.stem}.txt")
        all_classes.extend(labels)
        img_to_data[p] = (polygons_norm, labels)

    counter = Counter(all_classes)
    max_count = max(counter.values()) if counter else 0
    rare_classes = {c for c, count in counter.items() if count <= max_count * RARE_CLASS_THRESHOLD_RATIO}

    print(f"✅ พบภาพทั้งหมด: {len(img_files)} ภาพ")
    print(f"📊 สถิติคลาสต้นฉบับ: {dict(counter)}")

    # 2. เริ่มกระบวนการทำงาน
    for p in tqdm(img_files, desc="Processing Images"):
        polygons_norm, labels = img_to_data[p]
        img = cv2.imread(str(p))
        if img is None: continue

        orig_h, orig_w = img.shape[:2]

        # แปลงพิกัด Normalized (0-1) ให้เป็น Pixel จริงสำหรับการทำ Augmentation
        polygons_abs = [[(x*orig_w, y*orig_h) for x, y in poly] for poly in polygons_norm]

        # คัดลอกไฟล์เดิมลงโฟลเดอร์ใหม่ (ปรับขนาดให้ตรงตาม OUTPUT_SIZE)
        if COPY_ORIGINALS:
            img_resized = cv2.resize(img, (OUTPUT_SIZE[1], OUTPUT_SIZE[0]))
            cv2.imwrite(str(OUT_IMAGE_DIR / p.name), img_resized)
            # เซฟ label เดิม โดยไม่ต้องคำนวณพิกัดใหม่ เพราะเราใช้ค่า Normalized เดิมได้เลย
            save_yolo_obb_labels(OUT_LABEL_DIR / f"{p.stem}.txt", polygons_norm, labels, 1.0, 1.0)

        # ==========================================
        # ขั้นตอน Augmentation (ปั๊มภาพ)
        # ==========================================
        if not polygons_abs: continue

        n_aug = BASE_AUG_PER_IMAGE
        if any(c in rare_classes for c in labels):
            n_aug += MAX_EXTRA_AUG_FOR_RARE

        img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

        # แตกกลุ่ม OBB เป็นจุดๆ รวมกัน (1 กล่อง = 4 จุด) เพื่อให้ไลบรารีประมวลผลได้
        flat_keypoints = [pt for poly in polygons_abs for pt in poly]

        for i in range(n_aug):
            try:
                # สั่งหมุน/พลิกรูปภาพพร้อมจุดทั้งหมด
                augmented = TRANSFORM(image=img_rgb, keypoints=flat_keypoints)
                aug_img = cv2.cvtColor(augmented["image"], cv2.COLOR_RGB2BGR)
                aug_kp = augmented["keypoints"]

                # ประกอบร่างจุด 4 จุด กลับมาเป็น 1 กล่อง OBB เหมือนเดิม
                aug_polygons = [aug_kp[j:j+4] for j in range(0, len(aug_kp), 4)]

                fname = f"{p.stem}_aug{i}"
                cv2.imwrite(str(OUT_IMAGE_DIR / f"{fname}{p.suffix}"), aug_img)

                # เซฟ Label เป็นแบบ OBB โดยอิงจากขนาดภาพใหม่ (OUTPUT_SIZE)
                save_yolo_obb_labels(OUT_LABEL_DIR / f"{fname}.txt", aug_polygons, labels, OUTPUT_SIZE[1], OUTPUT_SIZE[0])

                if SAVE_PREVIEW and random.random() < 0.1:
                    preview = draw_bboxes_obb(aug_img, aug_polygons, labels)
                    cv2.imwrite(str(PREVIEW_DIR / f"{fname}_preview.jpg"), preview)

            except Exception as e:
                print(f"\n⚠️ ข้ามภาพ {p.name} augmentation ที่ {i} เนื่องจาก Error: {e}")
                continue

    print("\n✨ ปั๊มข้อมูลแบบ OBB เสร็จเรียบร้อย!")
    print(f"📁 บันทึกข้อมูลใหม่ไว้ที่: {OUTPUT_ROOT}")

# เริ่มรันโปรแกรม
run_augmentation()

