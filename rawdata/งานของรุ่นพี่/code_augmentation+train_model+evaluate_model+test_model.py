        res_rgb = cv2.cvtColor(res_plotted, cv2.COLOR_BGR2RGB)

        # ตั้งค่าแสดงผลให้ใหญ่และชัดเจน
        plt.figure(figsize=(12, 12))
        plt.imshow(res_rgb)
        plt.axis('off') # ปิดกรอบตัวเลขแกน X, Y
